use std::net::Ipv4Addr;

use crate::util;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HostsEntry {
    pub name: String,
    pub address: Ipv4Addr,
}

#[derive(Debug, Default)]
pub struct HostsParse {
    pub entries: Vec<HostsEntry>,
    pub warnings: Vec<String>,
}

/// Parse the `hosts(5)` format emitted by `uping --dns-zone`.
///
/// Each line is `<address> <name> [aliases...]`; `#` starts a comment.
/// Invalid lines are reported in `warnings` and skipped.
pub fn parse_hosts(input: &str) -> HostsParse {
    let mut parsed = HostsParse::default();
    for (index, line) in input.lines().enumerate() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let mut tokens = line.split_whitespace();
        let Some(address) = tokens.next() else {
            continue;
        };
        let address: Ipv4Addr = match address.parse() {
            Ok(address) => address,
            Err(_) => {
                parsed.warnings.push(format!(
                    "line {}: invalid IPv4 address '{address}'",
                    index + 1
                ));
                continue;
            }
        };
        let names: Vec<&str> = tokens.collect();
        if names.is_empty() {
            parsed
                .warnings
                .push(format!("line {}: no name after {address}", index + 1));
            continue;
        }
        for name in names {
            match util::validate_dns_name(name) {
                Ok(name) => parsed.entries.push(HostsEntry { name, address }),
                Err(err) => parsed.warnings.push(format!("line {}: {err}", index + 1)),
            }
        }
    }
    parsed
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_comments_aliases_and_invalid_lines() {
        let input = "\
# generated by uping --dns-zone
10.8.0.1 site1.internal.example.com site1-alias.internal.example.com
10.8.0.2 nas.internal.example.com   # the NAS
not-an-ip broken.internal.example.com
10.8.0.3 nas
";
        let parsed = parse_hosts(input);
        assert_eq!(parsed.entries.len(), 3);
        assert_eq!(parsed.entries[0].address, Ipv4Addr::new(10, 8, 0, 1));
        assert_eq!(parsed.entries[1].name, "site1-alias.internal.example.com");
        assert_eq!(parsed.entries[2].name, "nas.internal.example.com");
        assert_eq!(parsed.warnings.len(), 2);
    }
}
